"""
AI Security Monitoring REST API Endpoints (Phase 10)
Provides real-time threat intelligence, anomaly detection queries, and attack simulation.
"""
from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy.orm import Session
from datetime import datetime, timezone
from typing import List, Dict, Any, Optional
import uuid

from app.database.connection import get_db
from app.models.db_models import User, SecurityAlert
from app.security.rbac import get_current_user, require_roles
from app.ai_monitoring.anomaly_detector import AISecuritySentry

router = APIRouter(prefix="/api/v1/monitoring", tags=["AI Suspicious Activity Monitoring"])

@router.get("/alerts")
def get_security_alerts(
    resolved: Optional[bool] = Query(None),
    limit: int = Query(50, ge=1, le=200),
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
) -> Dict[str, Any]:
    """
    Returns detected security alerts generated by Isolation Forest & heuristic engine.
    """
    query = db.query(SecurityAlert)
    if resolved is not None:
        query = query.filter(SecurityAlert.is_resolved == resolved)

    total = query.count()
    alerts = query.order_by(SecurityAlert.created_at.desc()).limit(limit).all()

    return {
        "total_alerts": total,
        "returned_count": len(alerts),
        "alerts": [
            {
                "alert_id": a.alert_id,
                "user_id": a.user_id,
                "alert_type": a.alert_type,
                "severity": a.severity,
                "risk_score": float(a.risk_score),
                "detection_source": a.detection_source,
                "reason": a.reason,
                "is_resolved": a.is_resolved,
                "resolved_by": a.resolved_by,
                "resolved_at": a.resolved_at.isoformat() if a.resolved_at else None,
                "created_at": a.created_at.isoformat() if a.created_at else None
            }
            for a in alerts
        ]
    }

@router.get("/stats")
def get_monitoring_statistics(
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
) -> Dict[str, Any]:
    """
    Returns aggregate threat telemetry: active alert count, risk posture, severity breakdown.
    """
    all_alerts = db.query(SecurityAlert).all()
    unresolved = [a for a in all_alerts if not a.is_resolved]

    critical = sum(1 for a in unresolved if a.severity == "CRITICAL")
    high = sum(1 for a in unresolved if a.severity == "HIGH")
    medium = sum(1 for a in unresolved if a.severity == "MEDIUM")
    low = sum(1 for a in unresolved if a.severity == "LOW")

    avg_risk = sum(float(a.risk_score) for a in unresolved) / len(unresolved) if unresolved else 12.5

    return {
        "status": "OPERATIONAL",
        "total_alerts_historical": len(all_alerts),
        "active_unresolved_alerts": len(unresolved),
        "severity_breakdown": {
            "CRITICAL": critical,
            "HIGH": high,
            "MEDIUM": medium,
            "LOW": low
        },
        "average_unresolved_risk_score": round(avg_risk, 1),
        "overall_threat_level": "CRITICAL" if critical > 0 else ("ELEVATED" if high > 0 else "NOMINAL")
    }

@router.post("/resolve/{alert_id}")
def resolve_security_alert(
    alert_id: str,
    db: Session = Depends(get_db),
    current_user: User = Depends(require_roles(["ADMIN", "SUPER_ADMIN"]))
) -> Dict[str, Any]:
    """
    Marks a security alert as resolved by an authorized administrator.
    """
    alert = db.query(SecurityAlert).filter(SecurityAlert.alert_id == alert_id).first()
    if not alert:
        raise HTTPException(status_code=404, detail="Security alert not found.")

    now = datetime.now(timezone.utc)
    alert.is_resolved = True
    alert.resolved_by = current_user.user_id
    alert.resolved_at = now
    db.commit()

    return {
        "status": "SUCCESS",
        "message": f"Alert {alert_id} resolved by {current_user.username}.",
        "alert_id": alert_id,
        "resolved_at": now.isoformat()
    }

@router.post("/simulate-attack")
def simulate_attack_scenario(
    attack_type: str = Query(..., description="NOCTURNAL_BULK_DOWNLOAD, BRUTE_FORCE_DECRYPTION, or CREDENTIAL_STUFFING"),
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
) -> Dict[str, Any]:
    """
    Simulates attack patterns to demonstrate real-time AI anomaly detection:
    - NOCTURNAL_BULK_DOWNLOAD: Exfiltration burst at 03:00 UTC
    - BRUTE_FORCE_DECRYPTION: Repeated failed decryptions with invalid keys
    - CREDENTIAL_STUFFING: Rapid successive authentication failures
    """
    sentry = AISecuritySentry.get_instance()
    sim_type = attack_type.upper()

    if sim_type == "NOCTURNAL_BULK_DOWNLOAD":
        features = {
            "hour_of_day": 3.2,
            "is_nocturnal": True,
            "download_count_recent": 6,
            "request_rate_recent": 24,
            "failed_logins_recent": 0,
            "failed_decryptions_recent": 0,
            "privilege_level": 1
        }
    elif sim_type == "BRUTE_FORCE_DECRYPTION":
        features = {
            "hour_of_day": 14.5,
            "is_nocturnal": False,
            "download_count_recent": 1,
            "request_rate_recent": 18,
            "failed_logins_recent": 0,
            "failed_decryptions_recent": 5,
            "privilege_level": 1
        }
    elif sim_type == "CREDENTIAL_STUFFING":
        features = {
            "hour_of_day": 20.0,
            "is_nocturnal": False,
            "download_count_recent": 0,
            "request_rate_recent": 30,
            "failed_logins_recent": 6,
            "failed_decryptions_recent": 0,
            "privilege_level": 1
        }
    else:
        raise HTTPException(
            status_code=400,
            detail="Invalid attack_type. Must be: NOCTURNAL_BULK_DOWNLOAD, BRUTE_FORCE_DECRYPTION, or CREDENTIAL_STUFFING"
        )

    result = sentry.analyze_event(features, user_id=current_user.user_id, db=db)
    return {
        "status": "SIMULATED",
        "attack_type": sim_type,
        "detection_result": result
    }
